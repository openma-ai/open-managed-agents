import type { SandboxPort } from "@open-managed-agents/sandbox";
import { supportsCredentialEgress } from "@open-managed-agents/sandbox";
import type { CredentialEgressRevokeReason, RuntimeResourceScope, RuntimeResourceFence } from "@open-managed-agents/runtime-resource-contract";
import { RELAY_BUNDLE_GZIP_BASE64 } from "./relay-bundle.generated";
import { RELAY_PROTOCOL } from "./relay-protocol";
const quote = (text: string) => `'${text.replaceAll("'", "'\\''")}'`;
const installed = new WeakMap<object, string[]>();
const lifecycles = new WeakSet<object>();
let bundle: Promise<string> | undefined;
/** The relay is embedded (src/relay-bundle.generated.ts, regenerated by
 * scripts/build-relay-bundle.mjs) so hosts without a filesystem, such as a
 * Cloudflare Worker driving E2B, install the same bytes as Node hosts. */
export async function relayBundle(): Promise<string> {
  bundle ??= new Response(
    new Blob([Uint8Array.from(atob(RELAY_BUNDLE_GZIP_BASE64), (char) => char.charCodeAt(0))])
      .stream().pipeThrough(new DecompressionStream("gzip")),
  ).text();
  return bundle;
}
type Preparation = Parameters<typeof prepareSandboxEgress>[0];
/** Fits ProviderManagedRuntimeOptions.credentialEgress for every SandboxPort.
 * The host supplies current Session grants and revokes authorization remotely;
 * this adapter owns only the sandbox-side process/environment lifecycle.
 * Environment proxies are advisory, not provider-enforced network policy. */
export function createSandboxCredentialEgress(options: {
  resolve(input: { scope: RuntimeResourceScope; fence: RuntimeResourceFence; signal: AbortSignal }): Promise<{
    vaultIds: readonly string[];
    relay: Preparation["relay"];
    issueToken: Preparation["issueToken"];
    placeholders: Preparation["placeholders"];
  }>;
  revoke(input: { scope: RuntimeResourceScope; fence: RuntimeResourceFence; reason: CredentialEgressRevokeReason }): Promise<void>;
}) {
  return {
    capabilities: { enforcement: "advisory" as const, credentialMode: "live" as const, interceptedProtocols: ["https" as const] },
    async attach(input: { runtime: SandboxPort; scope: RuntimeResourceScope; fence: RuntimeResourceFence; requirement: "required" | "best_effort"; signal: AbortSignal }) {
      input.signal.throwIfAborted();
      if (input.requirement === "required") throw new Error("Sandbox environment proxy is advisory; required egress needs provider-native enforcement");
      const grant = await options.resolve(input);
      input.signal.throwIfAborted();
      await prepareSandboxEgress({ ...grant, sandbox: input.runtime, scope: { ...input.scope, vaultIds: grant.vaultIds } });
      input.signal.throwIfAborted();
    },
    async revoke(input: { runtime: SandboxPort; scope: RuntimeResourceScope; fence: RuntimeResourceFence; reason: CredentialEgressRevokeReason }) {
      try { await options.revoke(input); }
      finally { await clearSandboxEgress(input.runtime); }
    },
  };
}
/** Runs in the sandbox: `node -e ENSURE_RELAY <directory> <entry> <deliveryId>`.
 * A relay that is not healthy on this protocol (older version, exiting after
 * a 401, dead) is stopped and awaited first — so its exit can never remove
 * the new relay's ready.json — then a detached relay starts with the proxy
 * and CA variables unset. It then waits, bounded, until the relay reports
 * this deliveryId and binding.json is gone. A relay that dies with this
 * delivery still on disk (it decided to exit, e.g. on a 401, after it looked
 * healthy) is replaced, up to twice. A rejected binding, a newer delivery in
 * its place, or a timeout is a failure, never a fallback; failing removes
 * this delivery's file if it is still there, so no token is left on disk. */
const ENSURE_RELAY = `const fs=require('fs'),http=require('http'),cp=require('child_process'),path=require('path');
const [dir,entry,id]=process.argv.slice(1),readyFile=path.join(dir,'ready.json'),bindingFile=path.join(dir,'binding.json');
const read=()=>{try{return JSON.parse(fs.readFileSync(readyFile,'utf8'))}catch{return null}};
const alive=pid=>{try{process.kill(pid,0);return true}catch{return false}};
const healthy=r=>new Promise(done=>{if(!r||r.protocol!==${RELAY_PROTOCOL}||!alive(r.pid))return done(false);const q=http.get({host:'127.0.0.1',port:r.port,path:'/health',timeout:1000},s=>{s.resume();done(s.statusCode===200)});q.on('error',()=>done(false));q.on('timeout',()=>{q.destroy();done(false)})});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const delivered=()=>{try{return JSON.parse(fs.readFileSync(bindingFile,'utf8')).deliveryId}catch{return null}};
const fail=m=>{if(delivered()===id)try{fs.unlinkSync(bindingFile)}catch{}process.stdout.write('EGRESS_FAILED:'+m+String.fromCharCode(10));process.exit(1)};
const start=async r=>{if(r&&alive(r.pid)){try{process.kill(r.pid,'SIGTERM')}catch{}const t=Date.now();while(alive(r.pid)&&Date.now()-t<3000)await sleep(50);if(alive(r.pid))try{process.kill(r.pid,'SIGKILL')}catch{}}
try{fs.unlinkSync(readyFile)}catch{}
const env={...process.env};for(const k of ['HTTP_PROXY','HTTPS_PROXY','http_proxy','https_proxy','NODE_USE_ENV_PROXY','NODE_EXTRA_CA_CERTS'])delete env[k];
const log=fs.openSync(path.join(dir,'relay.log'),'a');const child=cp.spawn(process.execPath,[entry,dir],{detached:true,stdio:['ignore',log,log],env});child.unref();return child.pid};
(async()=>{let r=read();let pid=r&&r.pid;let restarts=0;
if(!await healthy(r))pid=await start(r);
const t=Date.now();for(;;){r=read();const consumed=!fs.existsSync(bindingFile);
if(r&&consumed&&r.bindingId===id&&await healthy(r)){process.stdout.write('EGRESS_READY:'+JSON.stringify({pid:r.pid,port:r.port,caFile:r.caFile,caBundleFile:r.caBundleFile})+String.fromCharCode(10));process.exit(0)}
if(r&&consumed&&r.bindingId!==id&&r.bindingError)fail(String(r.bindingError));
if(!consumed&&delivered()!==null&&delivered()!==id)fail('superseded by a newer delivery');
if(!consumed&&pid&&!alive(pid)){if(++restarts>2)fail('relay exited before it took the binding');pid=await start(null)}
if(Date.now()-t>8000)fail(consumed?'relay did not report this delivery':'binding was not consumed');
await sleep(50)}})().catch(e=>fail(e&&e.message||'error'))`;

export interface PreparedSandboxEgress { pid?: number; port?: number; caFile?: string }
export async function clearSandboxEgress(sandbox: SandboxPort): Promise<void> {
  if (supportsCredentialEgress(sandbox)) await sandbox.clearCredentialEgress();
  const previous = installed.get(sandbox) ?? [];
  if (previous.length) {
    if (!sandbox.setEnvVars) throw new Error("Sandbox cannot clear credential environment");
    await sandbox.setEnvVars(Object.fromEntries(previous.map(name => [name, ""])));
    installed.delete(sandbox);
  }
  if (!supportsCredentialEgress(sandbox)) await sandbox.exec("if [ -f .oma-egress/ready.json ]; then node -e 'try { process.kill(JSON.parse(require(\"fs\").readFileSync(\".oma-egress/ready.json\")).pid, \"SIGTERM\") } catch {}'; fi");
}
/** Provider-neutral lifecycle. Native adapters own interception; otherwise the
 * sandbox owns its bundled local process, CA files, readiness and cleanup. */
export async function prepareSandboxEgress(input: {
  sandbox: SandboxPort;
  scope: { workspaceId: string; sessionId: string; vaultIds: readonly string[] };
  relay: { endpoint: string; ca?: string; upstreamCa?: string };
  /** Managed hosts own cleanup separately from the revoked execution view. */
  registerCleanup?(cleanup: (sandbox: SandboxPort) => Promise<void>): void;
  /** A new sandbox token for this execution (the attempt's earlier ones stay valid). */
  issueToken(): Promise<string>;
  placeholders(scope: { workspaceId: string; sessionId: string; vaultIds: readonly string[] }): Promise<Record<string, string>>;
}): Promise<PreparedSandboxEgress> {
  const { sandbox, scope } = input;
  const previous = installed.get(sandbox) ?? [];
  const replace = async (env: Record<string, string>) => {
    if (!sandbox.setEnvVars) throw new Error("Sandbox cannot install credential environment");
    await sandbox.setEnvVars({ ...Object.fromEntries(previous.filter(name => !(name in env)).map(name => [name, ""])), ...env });
    installed.set(sandbox, Object.keys(env));
  };
  if (scope.vaultIds.length === 0) { await clearSandboxEgress(sandbox); return {}; }
  const placeholders = await input.placeholders(scope);
  // Vault placeholders in the env → the relay inspects every HTTPS host (local-relay.ts).
  const inspect = Object.values(placeholders).some(value => value.startsWith("oma_vault_"));
  const binding = { ...input.relay, sessionId: scope.sessionId, token: await input.issueToken(), ...(inspect ? { inspect } : {}) };
  if (new URL(binding.endpoint).protocol !== "https:") throw new Error("Credential relay endpoint must use HTTPS");
  if (supportsCredentialEgress(sandbox)) {
    await sandbox.prepareCredentialEgress(binding); await replace(placeholders); return {};
  }
  // No provider daemon API is assumed: exec + files work even on adapters
  // without startProcess. A bounded probe distinguishes failure from success.
  const source = await relayBundle();
  if (source === undefined) throw new Error("Sandbox relay bundle unavailable");
  const pathOutput = await sandbox.exec("mkdir -p .oma-egress && chmod 700 .oma-egress && printf 'EGRESS_DIR:' && cd .oma-egress && pwd", 5000);
  if (!/EGRESS_DIR:(\/[^\r\n]+)/u.test(pathOutput)) throw new Error("Sandbox cannot create local relay directory");
  // /workspace is the logical root shared by every adapter. writeFile returns
  // the executable path (local conformance adapters may map it to a host dir).
  const entry = await sandbox.writeFile("/workspace/.oma-egress/relay.cjs", source);
  const directory = entry.slice(0, entry.lastIndexOf("/"));
  // The token reaches the relay through one 0600 file that the relay deletes
  // once it holds the binding in memory; `deliveryId` (random, non-secret)
  // is how this installer sees that its delivery — not an older one — was taken.
  const deliveryId = [...crypto.getRandomValues(new Uint8Array(12))].map((b) => b.toString(16).padStart(2, "0")).join("");
  // A per-delivery staging name: two installers never write one file, and
  // the last mv (atomic rename) wins. A failed hand-over removes the staging file.
  const staging = `binding.${deliveryId}.next.json`;
  await sandbox.writeFile(`/workspace/.oma-egress/${staging}`, JSON.stringify({ ...binding, deliveryId }));
  const handedOver = await sandbox.exec(`chmod 600 ${quote(`${directory}/${staging}`)} && mv ${quote(`${directory}/${staging}`)} ${quote(`${directory}/binding.json`)} && echo EGRESS_DELIVERED || rm -f ${quote(`${directory}/${staging}`)}`, 5000);
  if (!handedOver.includes("EGRESS_DELIVERED")) throw new Error("Sandbox credential relay binding could not be delivered");
  const ready = `${directory}/ready.json`;
  if (sandbox.destroy && !lifecycles.has(sandbox)) {
    const cleanup = async (target: SandboxPort) => {
      await target.exec(`node -e ${quote(`try{process.kill(JSON.parse(require('fs').readFileSync(${JSON.stringify(ready)})).pid,'SIGTERM')}catch{}`)}`, 3000);
    };
    if (input.registerCleanup !== undefined) input.registerCleanup(cleanup);
    else {
      const destroy = sandbox.destroy.bind(sandbox);
      sandbox.destroy = async () => {
        try { await cleanup(sandbox); }
        finally { await destroy(); }
      };
    }
    lifecycles.add(sandbox);
  }
  const output = await sandbox.exec(`set -eu; command -v node >/dev/null; node -e ${quote(ENSURE_RELAY)} ${quote(directory)} ${quote(entry)} ${quote(deliveryId)}`, 15000);
  const failed = /EGRESS_FAILED:([^\n]*)/u.exec(output);
  if (failed) throw new Error(`Sandbox credential relay did not take its binding: ${failed[1]}`);
  const matched = /EGRESS_READY:(\{[^\n]+\})/u.exec(output);
  if (!matched) throw new Error("Sandbox credential relay installation/readiness failed");
  const state = JSON.parse(matched[1]!) as { pid: number; port: number; caFile: string; caBundleFile: string };
  if (!Number.isSafeInteger(state.pid) || !Number.isSafeInteger(state.port)) throw new Error("Invalid sandbox relay readiness");
  const proxy = `http://127.0.0.1:${state.port}`;
  await replace({ ...placeholders, HTTPS_PROXY: proxy, https_proxy: proxy, HTTP_PROXY: proxy, http_proxy: proxy,
    NO_PROXY: "localhost,127.0.0.1,::1", no_proxy: "localhost,127.0.0.1,::1", NODE_USE_ENV_PROXY: "1",
    NODE_EXTRA_CA_CERTS: state.caFile, SSL_CERT_FILE: state.caBundleFile, REQUESTS_CA_BUNDLE: state.caBundleFile,
    CURL_CA_BUNDLE: state.caBundleFile, GIT_SSL_CAINFO: state.caBundleFile, AWS_CA_BUNDLE: state.caBundleFile, DENO_CERT: state.caFile,
  });
  return state;
}
